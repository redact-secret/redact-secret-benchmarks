const range = (input: string, text: string) => {
  const at = input.indexOf(text);
  if (at < 0 || input.indexOf(text, at + 1) >= 0) throw new Error(`authored candidate is not a unique substring: ${text}`);
  const start = byteLength(input.slice(0, at));
  return { start, end: start + byteLength(text) };
};

