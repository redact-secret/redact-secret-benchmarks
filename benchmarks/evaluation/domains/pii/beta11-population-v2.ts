type C3Correction = { family: string; caseId: string; reasonCode: string; corrected: { publicFinding: boolean; oracle: C3Oracle } };
const c3Corrections = (c3CorrectionData as unknown as { corrections: C3Correction[] }).corrections;

export function buildC3PlanV3(family: 'pii:us:ssn' | 'pii:global:phone'): C3File {
  const predecessor = c3Files[family];
  const prior = structuredClone(predecessor.file);
  const corrections = c3Corrections.filter(row => row.family === family);
  const cases = prior.cases.map(row => {
    const correction = corrections.find(item => item.caseId === row.id);
    return correction ? { ...row, expected: { publicFinding: correction.corrected.publicFinding }, oracle: correction.corrected.oracle } : row;
  });
  const extra = family === 'pii:us:ssn' ? SSN_SPECS : PHONE_SPECS;
  cases.push(...extra);
  const file: C3File = {
    schemaVersion: 1, issue: 428, family, findingType: prior.findingType, familyContractVersion: prior.familyContractVersion,
    contextVocabulary: 'pii-context/v2', contract: { ...prior.contract, commit: B11_V2_CONTRACT.commit }, referenceValidator: prior.referenceValidator,
    id: prior.id.replace(/-v2$/, '-v3'), constructionPolicy: prior.constructionPolicy, nonGoals: prior.nonGoals,
    populations: prior.populations.map(row => ({ ...row, caseCount: cases.filter(item => item.view === row.id).length })),
    cases,
    derivedFrom: { id: prior.id, file: predecessor.path, fileSha256: fileSha256(predecessor.path), planCommitment: prior.frozen.planCommitment,
      method: 'Every predecessor case is kept with its id, candidate and context. The three #426 parenthesized-label corrections (evidence/901/426/pii-c3-reviewed-corrections-v1.json) become native authored truth; no US SSN or phone case changes under pii-context/v2; new independent cases are appended. No case was added, removed or relabelled from a scan.',
      relabeled: corrections.map(row => ({ caseId: row.caseId, from: prior.cases.find(item => item.id === row.caseId)!.oracle.sensitivity,
        to: row.corrected.oracle.sensitivity, basis: `redact-secret/redact-secret-benchmarks#426:${row.reasonCode}` })),
      addedCases: extra.map(row => row.id) },
    frozen: { planCommitment: '' },
  };
  file.frozen.planCommitment = c3PlanCommitment(file);
  return file;
}

