import type { ReviewLedger } from '../engine/review-ledger.ts';
import { canonical } from './canonical.ts';

/**
 * The legacy review-ledger decisions mapped to the canonical differential occurrences of the pinned methods run (#638,
 * docs/specs/qualification-adapter.md "The review-ledger re-key").
 *
 * The review ledger (`benchmarks/review-ledger.json`) holds decisions keyed by legacy occurrence ids: a hash of the legacy case
 * id, its source and the evidence of the disagreement. The methods run's review queue is keyed by canonical occurrence ids
 * (`sha256:<hex>`), so no decision applied to it. This file is the mapping, and ONLY the mapping: the legacy ledger stays the
 * source of every decision (status, note, evidence), the adapter resolves a canonical id to the legacy id and reads the decision
 * there, and nothing is invented. A canonical occurrence maps to a legacy one only when both name
 *
 *   - the same case: the legacy fixture joined to the canonical case by the content join of the parity report and the axis
 *     overlay (SHA-256 of the content, expected spans, fixture name, one to one), AND the very same bytes (the legacy occurrence's
 *     `contentHash` equals the canonical variant's `content_digest`);
 *   - the same peer scanner;
 *   - the same disagreement property (`peer-only`, `reference-only`, `range-disagreement`, `classification-disagreement`);
 *   - the same variant.
 *
 * Anything else stays unreviewed (an occurrence of a peer the legacy run never scanned, of a case the join does not pair, or of
 * a property the legacy run never observed) and is counted in `derivation`, never guessed. The legacy mutation entries have no
 * canonical counterpart (the canonical review queue holds differential occurrences only) and are counted as such.
 * Generated by `npm run qualification:ledger-rekey`; never hand-edited.
 */
export const LEDGER_REKEY_FILE = 'benchmarks/support/public-review-ledger-map.json';
export const LEDGER_REKEY_ID = 'credential-public-review-ledger-rekey-v1';
export const REKEY_POPULATION = 'public-evidence-snapshot';

export const UNMATCHED_CANONICAL = ['peer-not-in-legacy-run', 'case-not-joined', 'no-legacy-occurrence', 'content-differs', 'ambiguous'] as const;
export type UnmatchedCanonical = typeof UNMATCHED_CANONICAL[number];
export const UNMATCHED_LEGACY = ['case-not-joined', 'no-canonical-occurrence', 'content-differs', 'ambiguous', 'not-in-ledger'] as const;
export type UnmatchedLegacy = typeof UNMATCHED_LEGACY[number];

export interface LedgerRekey {
  schemaVersion: 1;
  id: typeof LEDGER_REKEY_ID;
  population: typeof REKEY_POPULATION;
  owner: 'redact-secret-benchmarks';
  note: string;
  snapshot: { corpusDigest: string; cases: number };
  /** The canonical methods run whose occurrence ids are mapped. */
  methodsRun: { run: string; semanticDigest: string };
  derivation: {
    join: string; occurrence: string;
    canonical: { occurrences: number; mapped: number; byPeer: Record<string, { occurrences: number; mapped: number }>; unmatched: Record<UnmatchedCanonical, number> };
    legacy: { differential: number; mapped: number; unmatched: Record<UnmatchedLegacy, number>; otherMethods: Record<string, number> };
    mappedByLegacyStatus: Record<string, number>;
  };
  /** Canonical occurrence id to the legacy ledger id whose decision applies to it. */
  occurrences: Record<string, string>;
}

export interface LegacyOccurrence { id: string; caseId: string; method: string; variant?: string; peer?: string; disagreement?: string; evidence?: { input?: { contentHash?: string } } }
export interface CanonicalOccurrence { id: string; case_id: string; method: string; variant: string; peer?: unknown; disagreement?: unknown }
export interface CanonicalVariant { case_id: string; variant: string; content_digest: string }

const byteOrder = (a: string, b: string) => Buffer.compare(Buffer.from(a), Buffer.from(b));
/**
 * The one vocabulary difference between the two queues: the legacy engine names the disagreement "only the product (the reference)
 * detected this" `redact-secret-only`; credential-eval names it `reference-only`. Same property (the reference reports a finding
 * the peer does not), different word; the other three kinds are spelled alike. Every legacy kind not listed is compared as is.
 */
export const LEGACY_PROPERTY: Record<string, string> = { 'redact-secret-only': 'reference-only' };
const propertyOf = (disagreement: unknown) => LEGACY_PROPERTY[String(disagreement ?? '')] ?? String(disagreement ?? '');
const keyOf = (caseId: string, variant: string | undefined, peer: unknown, disagreement: unknown) => JSON.stringify([caseId, variant ?? '', String(peer ?? ''), propertyOf(disagreement)]);
const digestHex = (digest: string) => digest.replace(/^sha256:/, '');
const METHOD = 'differential';

export interface RekeyInput {
  snapshot: { corpusDigest: string; cases: number };
  methodsRun: { run: string; semanticDigest: string; reviewQueue: CanonicalOccurrence[]; variants: CanonicalVariant[] };
  /** The legacy review queue of the development partition (`runEvaluation` reviewQueue), with the evidence of each occurrence. */
  legacyQueue: LegacyOccurrence[];
  /** Legacy fixture slug (`<category>--<fixture id>`) to the canonical case id it joins to, one to one. */
  joined: Map<string, string>;
  ledger: ReviewLedger;
}

/** Map the legacy decisions onto the canonical occurrences. Pure: the same inputs give the same mapping, whatever their order. */
export function buildLedgerRekey({ snapshot, methodsRun, legacyQueue, joined, ledger }: RekeyInput): LedgerRekey {
  const suffix = `--${METHOD}`;
  const canonicalCases = new Set(joined.values());
  const contentOfVariant = new Map(methodsRun.variants.map(v => [`${v.case_id}\u0000${v.variant}`, digestHex(v.content_digest)]));

  const legacyKeys = new Map<string, LegacyOccurrence[]>();
  const legacyByMethod: Record<string, number> = {};
  const legacyDifferential: LegacyOccurrence[] = [];
  for (const q of legacyQueue) {
    if (q.method !== METHOD) { legacyByMethod[q.method] = (legacyByMethod[q.method] ?? 0) + 1; continue; }
    legacyDifferential.push(q);
    const slug = q.caseId.endsWith(suffix) ? q.caseId.slice(0, -suffix.length) : q.caseId;
    const canonicalCase = joined.get(slug);
    if (!canonicalCase) continue;
    const key = keyOf(`${canonicalCase}${suffix}`, q.variant, q.peer, q.disagreement);
    legacyKeys.set(key, [...(legacyKeys.get(key) ?? []), q]);
  }
  const canonicalKeys = new Map<string, CanonicalOccurrence[]>();
  const differentialQueue = methodsRun.reviewQueue.filter(q => q.method === METHOD);
  for (const q of differentialQueue) {
    const key = keyOf(q.case_id, q.variant, q.peer, q.disagreement);
    canonicalKeys.set(key, [...(canonicalKeys.get(key) ?? []), q]);
  }
  const legacyPeers = new Set(legacyDifferential.map(q => String(q.peer ?? '')));

  const occurrences: Record<string, string> = {};
  const unmatchedCanonical = Object.fromEntries(UNMATCHED_CANONICAL.map(r => [r, 0])) as Record<UnmatchedCanonical, number>;
  const byPeer: Record<string, { occurrences: number; mapped: number }> = {};
  const mappedLegacy = new Set<string>();
  const legacyUnmatched = Object.fromEntries(UNMATCHED_LEGACY.map(r => [r, 0])) as Record<UnmatchedLegacy, number>;
  const mappedByLegacyStatus: Record<string, number> = {};
  const legacyUnmatchedIds = new Map<string, UnmatchedLegacy>();

  for (const q of differentialQueue) {
    const peer = String(q.peer ?? '');
    const row = (byPeer[peer] ??= { occurrences: 0, mapped: 0 });
    row.occurrences++;
    const key = keyOf(q.case_id, q.variant, q.peer, q.disagreement);
    const matches = legacyKeys.get(key) ?? [];
    const sameKey = canonicalKeys.get(key) ?? [];
    let reason: UnmatchedCanonical | undefined;
    if (!legacyPeers.has(peer)) reason = 'peer-not-in-legacy-run';
    else if (!canonicalCases.has(q.case_id.endsWith(suffix) ? q.case_id.slice(0, -suffix.length) : q.case_id)) reason = 'case-not-joined';
    else if (matches.length === 0) reason = 'no-legacy-occurrence';
    else if (matches.length > 1 || sameKey.length > 1) reason = 'ambiguous';
    else {
      const legacy = matches[0];
      const canonicalContent = contentOfVariant.get(`${q.case_id}\u0000${q.variant}`);
      if (!canonicalContent || !legacy.evidence?.input?.contentHash || legacy.evidence.input.contentHash !== canonicalContent) reason = 'content-differs';
      else if (!Object.hasOwn(ledger.entries, legacy.id)) { legacyUnmatchedIds.set(legacy.id, 'not-in-ledger'); reason = 'no-legacy-occurrence'; }
      else {
        occurrences[q.id] = legacy.id; mappedLegacy.add(legacy.id); row.mapped++;
        const status = ledger.entries[legacy.id].status;
        mappedByLegacyStatus[status] = (mappedByLegacyStatus[status] ?? 0) + 1;
      }
    }
    if (reason) unmatchedCanonical[reason]++;
  }
  for (const q of legacyDifferential) {
    if (mappedLegacy.has(q.id)) continue;
    const slug = q.caseId.endsWith(suffix) ? q.caseId.slice(0, -suffix.length) : q.caseId;
    const canonicalCase = joined.get(slug);
    let reason: UnmatchedLegacy;
    if (legacyUnmatchedIds.has(q.id)) reason = 'not-in-ledger';
    else if (!canonicalCase) reason = 'case-not-joined';
    else {
      const key = keyOf(`${canonicalCase}${suffix}`, q.variant, q.peer, q.disagreement);
      const peers = canonicalKeys.get(key) ?? [];
      if (peers.length === 0) reason = 'no-canonical-occurrence';
      else if (peers.length > 1 || (legacyKeys.get(key)?.length ?? 0) > 1) reason = 'ambiguous';
      else reason = 'content-differs';
    }
    legacyUnmatched[reason]++;
  }
  const sortedObject = <T>(o: Record<string, T>) => Object.fromEntries(Object.keys(o).sort(byteOrder).map(k => [k, o[k]]));
  return {
    schemaVersion: 1, id: LEDGER_REKEY_ID, population: REKEY_POPULATION, owner: 'redact-secret-benchmarks',
    note: 'Product-owned, generated by npm run qualification:ledger-rekey; never hand-edited. Maps a canonical differential occurrence of the pinned methods run to the legacy review-ledger entry made for the same case, peer and disagreement property; the legacy ledger stays the source of every decision. An unmapped occurrence is unreviewed.',
    snapshot,
    methodsRun: { run: methodsRun.run, semanticDigest: methodsRun.semanticDigest },
    derivation: {
      join: 'the legacy development fixture joined to the canonical case by the ordered content keys of the parity report (sha256(content)|expected spans|fixture name, then looser), one to one, and the occurrence bytes equal (legacy evidence.input.contentHash = canonical variant content_digest)',
      occurrence: 'canonical case, variant, peer scanner and disagreement property; the occurrence id itself is never compared',
      canonical: { occurrences: differentialQueue.length, mapped: Object.keys(occurrences).length, byPeer: sortedObject(byPeer), unmatched: unmatchedCanonical },
      legacy: { differential: legacyDifferential.length, mapped: mappedLegacy.size, unmatched: legacyUnmatched, otherMethods: sortedObject(legacyByMethod) },
      mappedByLegacyStatus: sortedObject(mappedByLegacyStatus),
    },
    occurrences: sortedObject(occurrences),
  };
}

export const serializeLedgerRekey = (map: LedgerRekey) => `${canonical(map)}\n`;

/** The ledger key a canonical occurrence is settled under: its own row if the ledger has one, else the legacy entry the re-key maps it to. */
export function ledgerSettledId(id: string, ledger: ReviewLedger, rekey?: LedgerRekey): string {
  if (Object.hasOwn(ledger.entries, id)) return id;
  const legacy = rekey && Object.hasOwn(rekey.occurrences, id) ? rekey.occurrences[id] : undefined;
  return legacy ?? id;
}

/** Structural validation of a parsed mapping against the legacy ledger. Returns problems. Reads no snapshot and no run. */
export function ledgerRekeyProblems(map: unknown, ledger: ReviewLedger): string[] {
  const problems: string[] = [];
  const m = map as Partial<LedgerRekey> | null;
  if (!m || typeof m !== 'object') return ['the mapping is not an object'];
  if (m.schemaVersion !== 1 || m.id !== LEDGER_REKEY_ID || m.population !== REKEY_POPULATION || m.owner !== 'redact-secret-benchmarks') problems.push('schemaVersion, id, population and owner must be the mapping identity');
  if (!/^sha256:[a-f0-9]{64}$/.test(m.snapshot?.corpusDigest ?? '')) problems.push('snapshot.corpusDigest must be sha256:<64 hex>');
  if (!/^sha256:[a-f0-9]{64}$/.test(m.methodsRun?.semanticDigest ?? '') || !m.methodsRun?.run) problems.push('methodsRun must name the run and its semantic digest (sha256:<64 hex>)');
  if (!m.occurrences || typeof m.occurrences !== 'object' || Array.isArray(m.occurrences)) return [...problems, 'occurrences is a required object'];
  const seen = new Map<string, string>();
  for (const [canonicalId, legacyId] of Object.entries(m.occurrences)) {
    if (!/^sha256:[a-f0-9]{64}$/.test(canonicalId)) problems.push(`occurrences key ${canonicalId.slice(0, 20)} is not a canonical occurrence id`);
    if (!/^[a-f0-9]{64}$/.test(legacyId)) problems.push(`occurrences[${canonicalId.slice(0, 20)}] is not a legacy ledger id`);
    else if (!Object.hasOwn(ledger.entries, legacyId)) problems.push(`occurrences[${canonicalId.slice(0, 20)}] names legacy id ${legacyId.slice(0, 12)}, which is not in benchmarks/review-ledger.json`);
    if (seen.has(legacyId)) problems.push(`legacy id ${legacyId.slice(0, 12)} is the decision of two canonical occurrences (${seen.get(legacyId)!.slice(0, 20)}, ${canonicalId.slice(0, 20)}); the mapping is one to one`);
    seen.set(legacyId, canonicalId);
  }
  const d = m.derivation;
  if (!d) problems.push('derivation is required');
  else {
    if (d.canonical?.mapped !== Object.keys(m.occurrences).length) problems.push('derivation.canonical.mapped must equal the number of mapped occurrences');
    if (d.legacy?.mapped !== Object.keys(m.occurrences).length) problems.push('derivation.legacy.mapped must equal the number of mapped occurrences');
    const unmatched = Object.values(d.canonical?.unmatched ?? {}).reduce((a, n) => a + n, 0);
    if (d.canonical && d.canonical.mapped + unmatched !== d.canonical.occurrences) problems.push('derivation.canonical: mapped + unmatched must equal occurrences');
    const legacyUnmatched = Object.values(d.legacy?.unmatched ?? {}).reduce((a, n) => a + n, 0);
    if (d.legacy && d.legacy.mapped + legacyUnmatched !== d.legacy.differential) problems.push('derivation.legacy: mapped + unmatched must equal differential');
  }
  return problems;
}
