import type { EvaluationCase } from '../engine/types.ts';
import { contracts } from '../lib/assessment.ts';
import { empiricalEvidence } from './empirical.ts';
import { CELL_IDS, PROFILE_IDS, fixtureProfileReport, fixtureProfiles, measureFixtureCells, profileClaim, type CellId, type FixtureProfileReport, type FixtureProfiles } from './profiles.ts';

/**
 * The generated, scanner-independent fixture-profile coverage report (#206):
 * one measurement of every registered family's cells, axis counts and debt,
 * checked in so CI can refuse drift between the corpus and what is published.
 */
export interface FixtureProfileCoverage {
  schemaVersion: 1;
  profilesVersion: number;
  familyCount: number;
  /** Families whose cells meet each profile's floors (cells only: tier, provider source and pending gates are separate). */
  cellsMetByProfile: Record<string, number>;
  families: ({ family: string; tier: string } & FixtureProfileReport)[];
}

export function buildFixtureProfileCoverage(cases: EvaluationCase[], profiles: FixtureProfiles = fixtureProfiles): FixtureProfileCoverage {
  const families = Object.keys(contracts).sort().map(family => ({
    family, tier: contracts[family].tier,
    ...fixtureProfileReport(profileClaim(contracts[family], empiricalEvidence(family).empiricalMode), measureFixtureCells(family, cases), profiles),
  }));
  const cellsMetByProfile = Object.fromEntries(PROFILE_IDS.map(id => [id, families.filter(f => f.cellsMet.includes(id)).length]));
  return { schemaVersion: 1, profilesVersion: profiles.profilesVersion, familyCount: families.length, cellsMetByProfile, families };
}

const CELL_TITLE: Record<CellId, string> = {
  totalFixtures: 'Total fixtures', positiveCases: 'Positive/context cases', benignControls: 'Non-twin benign controls', twinPairs: 'Twin pairs',
  positiveContextAxes: 'Positive-context axes', controlAxes: 'Control axes', confusionAxes: 'Confusion axes',
};
const cell = (value: number | undefined) => (value === undefined ? '—' : String(value));

/** The criteria table the spec embeds, generated so documentation cannot drift from `fixture-profiles.json`. */
export function profileCriteriaTable(profiles: FixtureProfiles = fixtureProfiles): string {
  const ids = PROFILE_IDS;
  const head = `| Cell | ${ids.map(id => profiles.profiles[id].title).join(' | ')} |`;
  const rule = `| --- | ${ids.map(() => '---:').join(' | ')} |`;
  const rows = CELL_IDS.map(c => `| ${CELL_TITLE[c]} | ${ids.map(id => cell(profiles.profiles[id].cells[c])).join(' | ')} |`);
  const extra = [
    `| Evidence tier required | ${ids.map(id => profiles.profiles[id].requiresEvidenceTier ?? '—').join(' | ')} |`,
    `| Enforcement | ${ids.map(id => profiles.profiles[id].enforcement).join(' | ')} |`,
  ];
  return [head, rule, ...rows, ...extra].join('\n');
}

export function renderFixtureProfileCoverage(report: FixtureProfileCoverage): string {
  const debtOf = (f: FixtureProfileCoverage['families'][number]) => f.debt.length ? f.debt.map(d => `${CELL_TITLE[d.cell].toLowerCase()} ${d.actual}/${d.required}`).join('; ') : 'none';
  const lines = [
    '# Fixture profile coverage',
    '',
    `Generated by \`npm run profiles:generate\` from the corpus and \`benchmarks/support/fixture-profiles.json\` (profiles version ${report.profilesVersion}). Do not edit: \`npm run profiles:check\` fails CI when this file differs from a fresh generation.`,
    '',
    'Cells and axes are counted from the corpus alone; no scanner runs. A family is measured against the profile it claims: `stable-documented` when its contract is T1 with a provider source, otherwise the arrival structure. Debt is the shortfall against that target, cell by cell.',
    '',
    'Meeting a profile\'s cells is not qualifying for it: tier, provider source and the observation and corroboration gates are separate, and the Wilson bounds published elsewhere are corpus-relative (see `docs/specs/support-status.md`).',
    '',
    '## Criteria',
    '',
    profileCriteriaTable(),
    '',
    '## Families meeting each profile\'s cells',
    '',
    '| Profile | Families | Of |',
    '| --- | ---: | ---: |',
    ...PROFILE_IDS.map(id => `| ${fixtureProfiles.profiles[id].title} | ${report.cellsMetByProfile[id]} | ${report.familyCount} |`),
    '',
    '## Per family',
    '',
    `| Family | Tier | Target | ${CELL_IDS.map(c => CELL_TITLE[c]).join(' | ')} | Remaining debt |`,
    `| --- | --- | --- | ${CELL_IDS.map(() => '---:').join(' | ')} | --- |`,
    ...report.families.map(f => `| ${f.family} | ${f.tier} | ${f.target} | ${CELL_IDS.map(c => f.cells[c]).join(' | ')} | ${debtOf(f)} |`),
    '',
  ];
  return lines.join('\n');
}
