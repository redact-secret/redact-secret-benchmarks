#!/usr/bin/env node
// Adopt one pii-eval engine build for the benchmark's public/synthetic PII measurement (#796). It derives every pin from a
// verified source and never types a digest:
//
//   node scripts/adopt-pii-engine.mjs --run=<pii-eval CI run id> --pii-eval=<git checkout containing the run's commit> [--write]
//
//   1. The pii-eval CI run must be a successful attempt-1 push to main; its engine artifact and its projection artifact are
//      downloaded read-only, their archive and member digests recomputed, and the engine's build-info and SHA256SUMS checked.
//   2. benchmarks/pii-eval-public-synthetic-source.json (transport) and the `build` block of both consumer pin files are
//      derived from that. The source archive digest is `git archive <commit> | sha256` of the given checkout.
//   3. The four benchmark populations' pins and the dual-run record in benchmarks/pii-eval-migration.json are derived from
//      benchmarks/pii-eval-population-dual-run/report.json (`npm run pii:population:dual-run -- --write`), never typed. A
//      replaced artifact, manifest or roster digest is kept in the pin's `retired*Digests`.
//   4. The synthetic-demo population (the CI projection artifact) is not repinned here: its artifact must still be the pinned
//      one, byte for byte, or the adoption stops, because a different demo population is a separate reviewed decision.
//
// Without --write it prints what it would change and exits 0; it never writes an owner acceptance, the authority files,
// a threshold or a support verdict, and it launches no scanner. The linux replay receipt and the rollback rehearsal are
// regenerated by their own commands afterwards (`pii:population:replay`, `pii:authority:rehearse -- --write`).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'redact-secret/pii-eval';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const fail = message => { throw new Error(`adopt-pii-engine: ${message}`); };
const readJson = file => JSON.parse(readFileSync(path.join(ROOT, file), 'utf8'));
const writeJson = (file, value) => writeFileSync(path.join(ROOT, file), `${JSON.stringify(value, null, 2)}\n`);
const gh = endpoint => JSON.parse(execFileSync('gh', ['api', endpoint], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 }));
const ghBytes = endpoint => execFileSync('gh', ['api', endpoint], { encoding: null, maxBuffer: 64 * 1024 * 1024 });
const arg = name => process.argv.find(a => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const write = process.argv.includes('--write');

const SOURCE = 'benchmarks/pii-eval-public-synthetic-source.json';
const DEMO_PINS = 'benchmarks/pii-eval-public-synthetic-pins.json';
const POP_PINS = 'benchmarks/pii-eval-population-pins.json';
const MIGRATION = 'benchmarks/pii-eval-migration.json';
const REPORT = 'benchmarks/pii-eval-population-dual-run/report.json';
const SCHEMA_V14 = 'schemas/pii-eval-public-synthetic-artifact-v1.4.json';

function members(zipFile) {
  const names = execFileSync('unzip', ['-Z1', zipFile], { encoding: 'utf8' }).trim().split('\n').filter(Boolean).sort();
  return Object.fromEntries(names.map(name => [name, execFileSync('unzip', ['-p', zipFile, name], { encoding: null, maxBuffer: 64 * 1024 * 1024 })]));
}

function transport(runId, dir) {
  const run = gh(`/repos/${REPO}/actions/runs/${runId}`);
  if (run.status !== 'completed' || run.conclusion !== 'success' || run.event !== 'push' || run.head_branch !== 'main' || run.run_attempt !== 1) fail(`run ${runId} is not a successful attempt-1 push to main`);
  const inventory = gh(`/repos/${REPO}/actions/runs/${runId}/artifacts?per_page=100`).artifacts;
  const pick = name => { const hit = inventory.filter(a => a.name === name); if (hit.length !== 1 || hit[0].expired) fail(`artifact ${name} is missing, duplicated or expired`); return hit[0]; };
  const found = {
    engine: pick(`pii-eval-engine-${run.head_sha}-linux-x86_64`),
    measurement: pick(`pii-eval-run-${runId}-1-projection`),
  };
  const out = { run, artifacts: {}, files: {} };
  for (const [role, item] of Object.entries(found)) {
    const bytes = ghBytes(`/repos/${REPO}/actions/artifacts/${item.id}/zip`);
    if (`sha256:${sha256(bytes)}` !== item.digest) fail(`${item.name}: downloaded archive differs from the API digest`);
    const file = path.join(dir, `${item.id}.zip`);
    writeFileSync(file, bytes);
    const files = members(file);
    out.files[role] = files;
    out.artifacts[role] = {
      id: item.id, name: item.name, sizeInBytes: item.size_in_bytes, archiveSha256: sha256(bytes), expiresAt: item.expires_at,
      members: Object.fromEntries(Object.entries(files).map(([name, body]) => [name, sha256(body)])),
    };
  }
  const info = JSON.parse(out.files.engine['build-info.json'].toString('utf8'));
  if (info.commit !== run.head_sha || info.runId !== String(runId) || info.target !== 'linux-x86_64' || info.binary.sha256 !== out.artifacts.engine.members['pii-eval']) fail('the engine build-info does not bind the run, commit and binary');
  const sums = out.files.engine.SHA256SUMS.toString('utf8');
  if (sums !== `${out.artifacts.engine.members['build-info.json']}  build-info.json\n${info.binary.sha256}  pii-eval\n`) fail('SHA256SUMS does not bind the build members');
  out.info = info;
  return out;
}

/** Record the canonical linux replay (pii-population-replay.yml) of the adopted engine: the receipt is the artifact of that run, byte for byte. */
function recordLinuxReplay() {
  const run = Number(arg('replay-run'));
  const receiptFile = path.resolve(arg('replay-receipt') ?? '');
  const meta = gh(`/repos/redact-secret/redact-secret-benchmarks/actions/runs/${run}`);
  if (meta.status !== 'completed' || meta.conclusion !== 'success' || meta.path !== '.github/workflows/pii-population-replay.yml' || meta.event !== 'workflow_dispatch') fail(`run ${run} is not a successful dispatch of pii-population-replay.yml`);
  const bytes = readFileSync(receiptFile);
  const receipt = JSON.parse(bytes.toString('utf8'));
  const record = readJson(MIGRATION);
  const pins = readJson(POP_PINS);
  if (receipt.engine.commit !== pins.build.commit || receipt.engine.binarySha256 !== pins.build.binarySha256 || receipt.canonical !== true || receipt.verdict.allBytesEqualCommitted !== true) fail('the receipt is not a canonical replay of the pinned engine');
  const target = path.join(ROOT, record.benchmarkPopulationDualRun.linuxReplay.path);
  if (write) writeFileSync(target, bytes);
  record.benchmarkPopulationDualRun.linuxReplay = { ...record.benchmarkPopulationDualRun.linuxReplay, sha256: sha256(bytes), runId: run, headSha: meta.head_sha, engineBinarySha256: receipt.engine.binarySha256, platform: receipt.engine.platform, result: 'equal' };
  if (write) writeJson(MIGRATION, record);
  console.log(JSON.stringify({ linuxReplay: record.benchmarkPopulationDualRun.linuxReplay, written: write }, null, 1));
}

function main() {
  if (arg('replay-run')) return recordLinuxReplay();
  const runId = Number(arg('run'));
  const checkout = arg('pii-eval');
  if (!Number.isSafeInteger(runId) || !checkout || !existsSync(path.join(checkout, '.git'))) fail('usage: --run=<id> --pii-eval=<checkout> [--write]');
  const dir = mkdtempSync(path.join(tmpdir(), 'adopt-pii-engine-'));
  const t = transport(runId, dir);
  const commit = t.run.head_sha;
  const archive = execFileSync('git', ['-C', checkout, 'archive', '--format=tar', commit], { encoding: null, maxBuffer: 1 << 28 });
  const build = { repository: REPO, commit, cargoLockSha256: t.info.toolchain.cargoLockSha256, binarySha256: t.info.binary.sha256, sourceArchiveSha256: sha256(archive) };

  // 1. Transport source. The durable copy of the (unchanged) demo projection moves with the run id.
  const source = readJson(SOURCE);
  const publicMember = source.publicArtifactMember;
  const demoDigest = source.artifacts.measurement.members[publicMember];
  if (t.artifacts.measurement.members[publicMember] !== demoDigest) fail('the demo projection artifact of the new run is not the pinned one: repinning the synthetic-demo population is a separate reviewed decision');
  const copyName = `tests/fixtures/pii-eval/ci-${runId}-projection.public-synthetic-artifact.json`;
  const next = {
    ...source,
    workflow: { ...source.workflow, runId, headSha: commit },
    artifacts: { engine: t.artifacts.engine, measurement: t.artifacts.measurement },
    buildInfo: { ...source.buildInfo, binaryBytes: t.info.binary.bytes, binaryVersion: t.info.binary.version, target: t.info.target, rustc: t.info.toolchain.rustc, rustToolchainFileSha256: t.info.toolchain.rustToolchainFileSha256 },
    durableCopy: { ...source.durableCopy, path: copyName },
  };

  // 2. Consumer pins.
  const demo = readJson(DEMO_PINS);
  demo.build = build;
  const pops = readJson(POP_PINS);
  const report = readJson(REPORT);
  if (report.identities.piiEval.commit !== commit) fail(`the dual-run report was made at ${report.identities.piiEval.commit}, not ${commit}`);
  pops.build = build;
  pops.artifactSchema = { ...pops.artifactSchema, version: report.identities.piiEval.artifactSchema };
  const retire = (list, old, current) => (old && old !== current && !list.includes(old) ? [...list, old] : list);
  for (const pin of pops.populations) {
    const entry = report.populations.find(p => p.view === pin.label);
    if (!entry) fail(`no dual-run entry for ${pin.label}`);
    pin.retiredArtifactDigests = retire(pin.retiredArtifactDigests, pin.artifactDigest, entry.artifact.semanticDigest);
    pin.retiredManifestDigests = retire(pin.retiredManifestDigests, pin.manifestDigest, entry.identities.manifestDigest);
    pin.artifactDigest = entry.artifact.semanticDigest;
    pin.manifestDigest = entry.identities.manifestDigest;
    pin.population.populationDigest = entry.identities.snapshotDigest;
    pin.projection.rosterDigest = entry.identities.rosterDigest;
  }

  // 3. The migration record: the engine pin, the readable schema, and the dual-run artifacts and coverage.
  const record = readJson(MIGRATION);
  record.pins.piiEvalProjection = commit;
  record.pins.piiEvalProjectionCargoLockSha256 = build.cargoLockSha256;
  const schemaFile = record.engine.artifactSchema;
  schemaFile.version = report.identities.piiEval.artifactSchema;
  schemaFile.readableVersions = [...new Set([...schemaFile.readableVersions, schemaFile.version])];
  schemaFile.schemaFiles[schemaFile.version] = { path: SCHEMA_V14, sha256: sha256(readFileSync(path.join(ROOT, SCHEMA_V14))), upstreamCommit: commit };
  const dual = record.benchmarkPopulationDualRun;
  dual.report.sha256 = sha256(readFileSync(path.join(ROOT, REPORT)));
  dual.engine = { commit, cargoLockSha256: build.cargoLockSha256, artifactSchema: schemaFile.version };
  for (const item of dual.artifacts) {
    const entry = report.populations.find(p => p.view === item.view);
    item.sha256 = entry.artifact.publicArtifactSha256;
    item.semanticDigest = entry.artifact.semanticDigest;
    item.snapshotDigest = entry.identities.snapshotDigest;
    item.manifestDigest = entry.identities.manifestDigest;
    item.rosterDigest = entry.identities.rosterDigest;
    item.cases = entry.conversion.benchmarkCases;
    item.carriedCases = entry.conversion.convertedCases;
    item.locatedCases = entry.rangeless.located;
    item.unresolvedRangeCases = entry.rangeless.cases;
    item.notRepresentableCases = entry.conversion.excludedCases;
  }
  dual.coverage = {
    benchmarkCases: dual.artifacts.reduce((n, a) => n + a.cases, 0),
    carriedCases: dual.artifacts.reduce((n, a) => n + a.carriedCases, 0),
    locatedCases: dual.artifacts.reduce((n, a) => n + a.locatedCases, 0),
    unresolvedRangeCases: dual.artifacts.reduce((n, a) => n + a.unresolvedRangeCases, 0),
    notRepresentableCases: dual.artifacts.reduce((n, a) => n + a.notRepresentableCases, 0),
    unresolvedRangeReason: 'authored identity not-established with no candidate range (pii-eval ADR 0017 and 0018, schema 1.4): carried range-less and reported unresolved, never a pass or a fail',
  };
  dual.unexplainedDifferences = report.verdict.unexplainedDifferences;
  record.publicationBinding.ciRun = { repository: REPO, runId, headSha: commit, engineArtifactId: t.artifacts.engine.id, measurementArtifactId: t.artifacts.measurement.id };
  record.publicationBinding.durableCopy = copyName;

  const summary = {
    commit, run: runId, engineArtifact: t.artifacts.engine.id, measurementArtifact: t.artifacts.measurement.id, binarySha256: build.binarySha256,
    sourceArchiveSha256: build.sourceArchiveSha256, populations: pops.populations.map(p => [p.label, p.artifactDigest.slice(0, 12)]), coverage: dual.coverage,
  };
  if (!write) { console.log(JSON.stringify({ dryRun: true, ...summary }, null, 1)); return; }
  writeJson(SOURCE, next);
  writeJson(DEMO_PINS, demo);
  writeJson(POP_PINS, pops);
  writeJson(MIGRATION, record);
  const oldCopy = path.join(ROOT, source.durableCopy.path), newCopy = path.join(ROOT, copyName);
  if (oldCopy !== newCopy) {
    if (sha256(readFileSync(oldCopy)) !== demoDigest) fail('the committed durable copy is not the pinned demo artifact');
    renameSync(oldCopy, newCopy);
  }
  console.log(JSON.stringify({ written: true, ...summary }, null, 1));
}

main();
