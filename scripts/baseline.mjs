// Baselines (§2.7): a released comparison point stored as (fixture, scanner) →
// outcome. The dashboard derives changed rows from the newest baseline and
// docs/release-comparison.md is generated from these files, never hand-edited.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { encodeOutcome } from '../benchmarks/lib/lattice.mjs';
import { kinds, tiers } from '../benchmarks/lib/assessment.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const save = args.indexOf('--save');
const report = args.includes('--report');
if ((save === -1 && !report) || args.some((a, i) => !['--save', '--report'].includes(a) && i !== save + 1)) {
  console.error('Usage: node scripts/baseline.mjs [--save <version>] [--report]');
  process.exit(1);
}
const baselineDir = path.join(root, 'baselines');
const readJson = async file => JSON.parse(await readFile(file, 'utf8'));

if (save !== -1) {
  const version = args[save + 1];
  if (!/^[0-9]+\.[0-9]+\.[0-9]+(?:-[A-Za-z0-9.]+)?$/.test(version)) throw new Error('Baseline version must be a semver string');
  const registry = await readJson(path.join(root, 'benchmarks/categories.json'));
  const run = await readJson(path.join(root, 'public/results/run.json'));
  if (run.partial) throw new Error('Refusing to baseline a partial run; run npm run bench for every suite');
  const baseline = { schemaVersion: 1, version, runId: run.runId, savedAt: new Date().toISOString(), revision: run.revision, scanners: run.scannerVersions, corpusHashes: {}, groups: {}, rows: {} };
  for (const category of registry) {
    const r = await readJson(path.join(root, `public/results/${category.id}.json`));
    if (r.schemaVersion !== 4 || r.runId !== run.runId) throw new Error(`Report ${category.id} is not from run ${run.runId}`);
    baseline.corpusHashes[category.id] = r.corpusHash;
    for (const scanner of r.scanners) {
      if (scanner.status !== 'complete') throw new Error(`Scanner ${scanner.id} did not complete ${category.id}`);
      baseline.groups[category.id] ??= {};
      baseline.groups[category.id][scanner.id] = scanner.groups;
      for (const row of scanner.rows) {
        const slug = `${category.id}--${row.id}`;
        baseline.rows[slug] ??= {};
        baseline.rows[slug][scanner.id] = encodeOutcome(row);
      }
    }
  }
  await writeFile(path.join(baselineDir, `${version}.json`), JSON.stringify(baseline, null, 2) + '\n');
  console.log(`Saved baselines/${version}.json: ${Object.keys(baseline.rows).length} fixtures × ${Object.keys(baseline.scanners).length} scanners from run ${run.runId}`);
}

if (report) {
  const files = (await readdir(baselineDir)).filter(f => f.endsWith('.json')).sort();
  const baselines = await Promise.all(files.map(f => readJson(path.join(baselineDir, f))));
  const registry = await readJson(path.join(root, 'benchmarks/categories.json'));
  const pct = v => (v == null ? '—' : `${(v * 100).toFixed(1)}%`);
  const lines = ['# Release comparison', '', '> Generated by `npm run baseline:report` from `baselines/*.json`. Do not edit by hand; save a new baseline with `npm run baseline -- --save <version>` after a complete `npm run bench`.', '', 'Measurement protocol v4 (`docs/measurement-v4.md`). Numbers are corpus-relative per (kind × tier) group on one run id; they are not accuracy and not a product ranking. T0 rows are unscored.', ''];
  for (const b of baselines) {
    lines.push(`## ${b.version}`, '', `Run \`${b.runId}\` · revision \`${b.revision}\` · saved ${b.savedAt}`, '', 'Scanner versions: ' + Object.entries(b.scanners).map(([id, v]) => `${id} ${v}`).join(' · '), '');
    const totals = {};
    for (const category of Object.values(b.groups)) for (const [scanner, groups] of Object.entries(category)) for (const [key, g] of Object.entries(groups)) {
      const t = (totals[key] ??= {})[scanner] ??= { files: 0, spans: 0, leakedSpans: 0, flaggedFiles: 0, collateralBytes: 0, secretBytes: 0, pairs: 0, discriminated: 0 };
      t.files += g.files;
      if (g.spans != null) { t.spans += g.spans; t.leakedSpans += g.leakedSpans; t.collateralBytes += g.collateralBytes; t.secretBytes += g.secretBytes; t.pairs += g.twins.pairs; t.discriminated += g.twins.discriminated; }
      if (g.flaggedFiles != null) t.flaggedFiles += g.flaggedFiles;
    }
    for (const key of Object.keys(totals).sort()) {
      const [kind, tier] = key.split('/');
      lines.push(`### ${kinds[kind]?.title ?? 'Pending'} · ${tier} ${tiers[tier].title}`, '');
      if (kind === 'pending') { lines.push(`${Object.values(totals[key])[0].files} files, unscored.`, ''); continue; }
      if (kind === 'must-not-flag') {
        lines.push('| Scanner | Files | False alarms | Rate |', '| --- | ---: | ---: | ---: |');
        for (const [scanner, t] of Object.entries(totals[key])) lines.push(`| ${scanner} | ${t.files} | ${t.flaggedFiles} | ${pct(t.files ? t.flaggedFiles / t.files : null)} |`);
      } else {
        lines.push('| Scanner | Files | Spans | Leaked spans | Leaked span rate | Collateral ratio | Twins discriminated |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: |');
        for (const [scanner, t] of Object.entries(totals[key])) lines.push(`| ${scanner} | ${t.files} | ${t.spans} | ${t.leakedSpans} | ${pct(t.spans ? t.leakedSpans / t.spans : null)} | ${t.secretBytes ? (t.collateralBytes / t.secretBytes).toFixed(3) : '—'} | ${t.pairs ? `${t.discriminated} / ${t.pairs}` : '—'} |`);
      }
      lines.push('', 'Suites are summed here for readability only; per-suite groups are in the baseline file and the dashboard never sums across suites with different run ids.', '');
    }
  }
  for (let i = 1; i < baselines.length; i++) {
    const before = baselines[i - 1], after = baselines[i];
    const changed = [];
    for (const [slug, scanners] of Object.entries(after.rows)) for (const [scanner, outcome] of Object.entries(scanners)) {
      const previous = before.rows[slug]?.[scanner];
      if (previous !== undefined && previous !== outcome) changed.push(`| ${slug} | ${scanner} | \`${previous}\` | \`${outcome}\` |`);
    }
    const added = Object.keys(after.rows).filter(s => !before.rows[s]).length;
    const removed = Object.keys(before.rows).filter(s => !after.rows[s]).length;
    lines.push(`## Changed rows: ${before.version} → ${after.version}`, '', `${changed.length} (fixture, scanner) outcomes changed · ${added} fixtures added · ${removed} fixtures removed. Corpus hashes ${registry.every(c => before.corpusHashes[c.id] === after.corpusHashes[c.id]) ? 'unchanged' : 'differ; only fixtures present in both baselines are compared'}.`, '');
    if (changed.length) lines.push('| Fixture | Scanner | Before | After |', '| --- | --- | --- | --- |', ...changed, '');
  }
  await writeFile(path.join(root, 'docs/release-comparison.md'), lines.join('\n') + '\n');
  console.log(`Wrote docs/release-comparison.md from ${baselines.length} baseline(s)`);
}
